'use client'

import { useId, useState } from 'react'

import type { ResumeFeedback, StoredResumeFeedback } from '@/lib/resume-feedback'
import styles from '@/app/ui.module.css'

const NETWORK_ERROR = "Couldn't reach the server. Please try again."
const GENERIC_ERROR = 'Something went wrong while generating feedback. Please try again.'

function isStringArray(value: unknown): value is string[] {
  return Array.isArray(value) && value.every((item) => typeof item === 'string')
}

function isStoredFeedback(value: unknown): value is StoredResumeFeedback {
  if (!value || typeof value !== 'object') return false
  const record = value as Record<string, unknown>
  const feedback = record.feedback as Partial<ResumeFeedback> | null | undefined
  return (
    typeof record.model === 'string' &&
    typeof record.createdAt === 'string' &&
    !!feedback &&
    typeof feedback.summary === 'string' &&
    isStringArray(feedback.strengths) &&
    isStringArray(feedback.improvements)
  )
}

type RequestResult = { ok: true; feedback: StoredResumeFeedback } | { ok: false; error: string }

async function requestFeedback(resumeId: string): Promise<RequestResult> {
  let response: Response
  try {
    response = await fetch(`/api/resumes/${encodeURIComponent(resumeId)}/feedback`, { method: 'POST' })
  } catch {
    return { ok: false, error: NETWORK_ERROR }
  }

  let body: unknown
  try {
    body = await response.json()
  } catch {
    return { ok: false, error: GENERIC_ERROR }
  }

  if (!response.ok) {
    const message = body && typeof body === 'object' ? (body as { error?: unknown }).error : null
    return { ok: false, error: typeof message === 'string' && message.trim() ? message : GENERIC_ERROR }
  }

  return isStoredFeedback(body) ? { ok: true, feedback: body } : { ok: false, error: GENERIC_ERROR }
}

function formatGeneratedAt(iso: string): string {
  const date = new Date(iso)
  return Number.isNaN(date.getTime())
    ? iso
    : date.toLocaleString(undefined, { dateStyle: 'medium', timeStyle: 'short' })
}

export function ResumeFeedbackPanel({
  resumeId,
  resumeName,
  initialFeedback,
}: {
  resumeId: string
  resumeName: string
  initialFeedback: StoredResumeFeedback | null
}) {
  const [stored, setStored] = useState<StoredResumeFeedback | null>(initialFeedback)
  // Saved feedback starts collapsed so a long resume list stays scannable;
  // freshly generated feedback opens automatically.
  const [expanded, setExpanded] = useState(false)
  const [pending, setPending] = useState(false)
  const [error, setError] = useState<string | null>(null)
  const contentId = useId()

  async function generate() {
    setPending(true)
    setError(null)
    const result = await requestFeedback(resumeId)
    setPending(false)
    if (result.ok) {
      setStored(result.feedback)
      setExpanded(true)
    } else {
      // Previously shown feedback (if any) stays visible.
      setError(result.error)
    }
  }

  return (
    <section className={styles.feedback} aria-label={`AI feedback for ${resumeName}`}>
      <h3>AI feedback</h3>

      <div className={styles.feedbackActions}>
        <button
          type="button"
          className={styles.secondary}
          onClick={generate}
          disabled={pending}
          aria-busy={pending}
        >
          {stored ? 'Regenerate feedback' : 'Get AI feedback'}
        </button>
        {stored && (
          <button
            type="button"
            className={styles.secondary}
            aria-expanded={expanded}
            aria-controls={contentId}
            onClick={() => setExpanded((open) => !open)}
          >
            {expanded ? 'Hide feedback' : 'Show feedback'}
          </button>
        )}
      </div>

      <p role="status" className={`${styles.muted} ${styles.feedbackStatus}`}>
        {pending ? 'Analyzing your resume… this can take up to a minute.' : ''}
      </p>
      {error && <p role="alert">{error}</p>}

      {stored && (
        <div id={contentId} hidden={!expanded} className={styles.feedbackBody}>
          <p>{stored.feedback.summary}</p>

          {stored.feedback.strengths.length > 0 && (
            <>
              <h4>Strengths</h4>
              <ul>
                {stored.feedback.strengths.map((item, index) => (
                  <li key={index}>{item}</li>
                ))}
              </ul>
            </>
          )}

          {stored.feedback.improvements.length > 0 && (
            <>
              <h4>Suggested improvements</h4>
              <ul>
                {stored.feedback.improvements.map((item, index) => (
                  <li key={index}>{item}</li>
                ))}
              </ul>
            </>
          )}

          <p className={styles.muted}>
            Generated by {stored.model} on{' '}
            <time dateTime={stored.createdAt} suppressHydrationWarning>
              {formatGeneratedAt(stored.createdAt)}
            </time>
          </p>
          <p className={styles.muted}>AI-generated suggestions — review before making changes.</p>
        </div>
      )}
    </section>
  )
}
