import { test, expect } from '@playwright/test'
import { startPreview } from '../fixtures/recruiter-preview.mjs'
let preview
test.beforeAll(async () => { preview = await startPreview() })
test.afterAll(async () => { await preview?.close() })

const pdf = name => ({ name, mimeType: 'application/pdf', buffer: Buffer.from(`%PDF-1.4\n% ${name}\n%%EOF\n`) })
const jobId = '00000000-0000-0000-0000-0000000000aa'

// US-21. The fake backend has no Ollama, so each test mocks /api/job-matches in the browser.
async function signIn(page) {
  const base = `http://127.0.0.1:${preview.appPort}`
  await page.goto(base + '/login')
  await page.getByLabel('Email').fill('jobseeker@example.test')
  await page.getByLabel('Password').fill('any-password')
  await page.getByRole('button', { name: 'Log in' }).click()
  await expect(page).toHaveURL(base + '/dashboard')
  return base
}

test('job seeker without a resume is asked to upload one first', async ({ page }) => {
  const base = await signIn(page)
  await page.goto(base + '/job-matches')
  await expect(page.getByRole('heading', { name: 'AI job matches', level: 1 })).toBeVisible()
  await expect(page.getByRole('heading', { name: 'Upload a resume first' })).toBeVisible()
  await expect(page.getByText(/Matches are not saved and recruiters never see them/)).toBeVisible()
})

test('job seeker finds AI job matches with reasons, gaps and errors handled', async ({ page }) => {
  const base = await signIn(page)
  await page.goto(base + '/resumes')
  await page.getByLabel('Upload resumes (PDF or DOCX, up to 5 MB each)').setInputFiles([pdf('matches.pdf')])
  await page.getByRole('button', { name: 'Upload', exact: true }).click()
  await expect(page.getByText('Resume uploaded.')).toBeVisible()

  await page.getByRole('link', { name: 'AI matches' }).click()
  await expect(page).toHaveURL(base + '/job-matches')
  await expect(page.getByLabel('Resume')).toHaveValue(/[0-9a-f-]{36}/)

  // AI service down: a clear error and no results.
  await page.route('**/api/job-matches', route => route.fulfill({ status: 503, json: {
    error: 'The AI matching service is unavailable right now. Please try again later.', code: 'ai_unavailable',
  } }))
  await page.getByRole('button', { name: 'Find matches' }).click()
  await expect(page.getByRole('main').getByRole('alert')).toHaveText('The AI matching service is unavailable right now. Please try again later.')
  await page.unroute('**/api/job-matches')

  let release, requested
  const gate = new Promise(resolve => { release = resolve })
  await page.route('**/api/job-matches', async route => {
    requested = route.request()
    await gate
    await route.fulfill({ json: {
      matches: [{ jobId, title: 'Frontend Developer', company: 'Acme', location: 'Montreal, Quebec, Canada', score: 82,
        reasons: ['Five years of React and TypeScript'], missingSkills: ['GraphQL'] }],
      considered: 12, model: 'llama3.1:8b',
    } })
  })
  await page.getByRole('button', { name: 'Find matches' }).click()
  await expect(page.getByRole('status').filter({ hasText: 'Matching your resume against open postings' })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Find matches' })).toBeDisabled()
  release()

  await expect(page.getByText('1 match from 12 open postings.')).toBeVisible()
  expect(requested.method()).toBe('POST')
  expect(requested.postDataJSON().resumeId).toMatch(/^[0-9a-f-]{36}$/)
  await expect(page.getByRole('heading', { name: 'Frontend Developer', level: 2 })).toBeVisible()
  await expect(page.getByText('Strong fit')).toBeVisible()
  await expect(page.getByText('Five years of React and TypeScript', { exact: true })).toBeVisible()
  await expect(page.getByText('GraphQL', { exact: true })).toBeVisible()
  await expect(page.getByRole('heading', { name: 'Skills to strengthen' })).toBeVisible()
  await expect(page.getByRole('link', { name: 'Apply' })).toHaveAttribute('href', `/jobs/${jobId}/apply?returnTo=%2Fjob-matches`)
  await expect(page.getByText(/Generated by llama3\.1:8b/)).toBeVisible()
  await page.unroute('**/api/job-matches')

  // Nothing overlaps: an empty state, not an error.
  await page.route('**/api/job-matches', route => route.fulfill({ json: { matches: [], considered: 3, model: null } }))
  await page.getByRole('button', { name: 'Find matches again' }).click()
  await expect(page.getByRole('heading', { name: 'No matches yet' })).toBeVisible()
})

test('recruiters cannot use AI job matches', async ({ page }) => {
  const base = `http://127.0.0.1:${preview.appPort}`
  await page.goto(base + '/login')
  await page.getByLabel('Email').fill('recruiter@example.test')
  await page.getByLabel('Password').fill('any-password')
  await page.getByRole('button', { name: 'Log in' }).click()
  await expect(page).not.toHaveURL(/\/login/)
  await page.goto(base + '/job-matches')
  await expect(page.getByText('Only job seekers can get job matches.')).toBeVisible()
  await expect(page.getByRole('link', { name: 'AI matches' })).toHaveCount(0)
})
