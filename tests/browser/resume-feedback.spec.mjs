import { test, expect } from '@playwright/test'
import { startPreview } from '../fixtures/recruiter-preview.mjs'
let preview
test.beforeAll(async () => { preview = await startPreview() })
test.afterAll(async () => { await preview?.close() })

const pdf = name => ({ name, mimeType: 'application/pdf', buffer: Buffer.from(`%PDF-1.4\n% ${name}\n%%EOF\n`) })

// Signs in the demo job seeker and makes sure one resume is listed. The fake
// backend has no Ollama, so each test mocks the feedback endpoint in the browser.
async function openResume(page, name) {
  const errors = []
  page.on('console', message => { if (message.type() === 'error') errors.push(message.text()) })
  page.on('pageerror', error => errors.push(error.message))
  const base = `http://127.0.0.1:${preview.appPort}`
  await page.goto(base + '/login')
  await page.getByLabel('Email').fill('jobseeker@example.test')
  await page.getByLabel('Password').fill('any-password')
  await page.getByRole('button', { name: 'Log in' }).click()
  await expect(page).toHaveURL(base + '/')
  await page.goto(base + '/resumes')
  await page.getByLabel('Upload resumes (PDF or DOCX, up to 5 MB each)').setInputFiles([pdf(name)])
  await page.getByRole('button', { name: 'Upload', exact: true }).click()
  await expect(page.getByText('Resume uploaded.')).toBeVisible()
  const panel = page.getByRole('region', { name: `AI feedback for ${name}` })
  await expect(panel.getByRole('heading', { name: 'AI feedback', level: 3 })).toBeVisible()
  return { panel, errors }
}

test('job seeker gets AI feedback for a resume', async ({ page }) => {
  const { panel, errors } = await openResume(page, 'feedback-happy.pdf')
  await expect(panel.getByRole('button', { name: 'Show feedback' })).toHaveCount(0)

  let release, requested
  const gate = new Promise(resolve => { release = resolve })
  await page.route('**/api/resumes/*/feedback', async route => {
    requested = route.request()
    await gate
    await route.fulfill({ json: {
      feedback: { summary: 'A focused backend resume with clear impact.', strengths: ['Quantified achievements', 'Concise layout'], improvements: ['Add a link to your GitHub profile'] },
      model: 'llama3.1:8b', createdAt: '2026-11-08T15:30:00Z',
    } })
  })

  await panel.getByRole('button', { name: 'Get AI feedback' }).click()
  await expect(panel.getByRole('status')).toHaveText('Analyzing your resume… this can take up to a minute.')
  await expect(panel.getByRole('button', { name: 'Get AI feedback' })).toBeDisabled()
  release()

  await expect(panel.getByText('A focused backend resume with clear impact.')).toBeVisible()
  await expect(panel.getByRole('status')).toHaveText('')
  expect(requested.method()).toBe('POST')
  expect(requested.url()).toMatch(/\/api\/resumes\/[0-9a-f-]{36}\/feedback$/)
  await expect(panel.getByRole('heading', { name: 'Strengths', level: 4 })).toBeVisible()
  await expect(panel.getByRole('heading', { name: 'Suggested improvements', level: 4 })).toBeVisible()
  for (const item of ['Quantified achievements', 'Concise layout', 'Add a link to your GitHub profile']) {
    await expect(panel.getByRole('listitem').filter({ hasText: item })).toBeVisible()
  }
  await expect(panel.getByText(/^Generated by llama3\.1:8b on /)).toBeVisible()
  await expect(panel.getByRole('button', { name: 'Regenerate feedback' })).toBeEnabled()
  await expect(panel.getByRole('button', { name: 'Get AI feedback' })).toHaveCount(0)
  await expect(panel.getByRole('alert')).toHaveCount(0)

  // New feedback opens automatically and can be collapsed.
  const toggle = panel.getByRole('button', { name: 'Hide feedback' })
  await expect(toggle).toHaveAttribute('aria-expanded', 'true')
  await toggle.click()
  await expect(panel.getByText('A focused backend resume with clear impact.')).toBeHidden()
  await expect(panel.getByRole('button', { name: 'Show feedback' })).toHaveAttribute('aria-expanded', 'false')

  expect(errors).toEqual([])
})

test('an unavailable AI service shows the server error and no feedback', async ({ page }) => {
  const { panel, errors } = await openResume(page, 'feedback-down.pdf')
  await page.route('**/api/resumes/*/feedback', route => route.fulfill({
    status: 503,
    json: { error: 'The AI feedback service is unavailable right now. Please try again later.', code: 'ai_unavailable' },
  }))

  await panel.getByRole('button', { name: 'Get AI feedback' }).click()
  await expect(panel.getByRole('alert')).toHaveText('The AI feedback service is unavailable right now. Please try again later.')
  await expect(panel.getByRole('status')).toHaveText('')
  await expect(panel.getByRole('button', { name: 'Get AI feedback' })).toBeEnabled()
  await expect(panel.getByRole('heading', { name: 'Strengths' })).toHaveCount(0)
  await expect(panel.getByRole('button', { name: /^(Show|Hide) feedback$/ })).toHaveCount(0)

  // The browser logs failed fetches (503) as console errors; nothing else should appear.
  expect(errors.filter(text => !/status of 503/.test(text))).toEqual([])
})
